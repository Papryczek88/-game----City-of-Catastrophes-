use std::fmt::Display;

#[derive(Clone, Copy, PartialEq)]
pub enum Jezyk {
    En,
    Pl,
    De,
    Pt,
}

pub const JEZYKI: [Jezyk; 4] = [Jezyk::En, Jezyk::Pl, Jezyk::De, Jezyk::Pt];

impl Jezyk {
    pub fn idx(self) -> usize {
        match self {
            Jezyk::En => 0,
            Jezyk::Pl => 1,
            Jezyk::De => 2,
            Jezyk::Pt => 3,
        }
    }

    /// Nazwa jezyka w tym samym jezyku.
    pub fn nazwa(self) -> &'static str {
        ["English", "Polski", "Deutsch", "Português (Portugal)"][self.idx()]
    }

    pub fn kod(self) -> &'static str {
        ["en", "pl", "de", "pt"][self.idx()]
    }

    pub fn z_kodu(kod: &str) -> Option<Jezyk> {
        match kod {
            "en" => Some(Jezyk::En),
            "pl" => Some(Jezyk::Pl),
            "de" => Some(Jezyk::De),
            "pt" => Some(Jezyk::Pt),
            _ => None,
        }
    }
}

/// Wstawia kolejne argumenty w miejsce `{}` w szablonie.
pub fn fill(szablon: &str, arg: &[&dyn Display]) -> String {
    let mut wynik = String::new();
    let mut reszta = szablon;
    let mut i = 0;
    while let Some(poz) = reszta.find("{}") {
        wynik.push_str(&reszta[..poz]);
        if i < arg.len() {
            wynik.push_str(&arg[i].to_string());
        }
        i += 1;
        reszta = &reszta[poz + 2..];
    }
    wynik.push_str(reszta);
    wynik
}

